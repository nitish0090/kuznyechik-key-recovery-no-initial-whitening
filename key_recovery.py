# Reproducibility experiment from the paper
# ============================================================

def main():
    print("=" * 72)
    print("Kuznyechik integral distinguisher and 4-round subkey recovery")
    print("Reduced model without initial key whitening")
    print("=" * 72)

    # The revised paper states that the local keys K1,...,K4 are
    # instantiated by the first four subkeys generated by the
    # standard Kuznyechik key schedule.
    full_schedule = standard_key_expansion(REFERENCE_MASTER_KEY)
    local_keys = full_schedule[:4]

    real_k4_prime = L_inv(local_keys[3])

    print("\nReference master key:")
    print("8899aabbccddeeff0011223344556677")
    print("fedcba98765432100123456789abcdef")

    print("\nLocal reduced-model subkeys:")
    for i, key in enumerate(local_keys, start=1):
        print(f"K{i}  = {block_to_hex(key)}")

    print(f"\nK4' = L^(-1)(K4) = {block_to_hex(real_k4_prime)}")

    # Two independent first-order structures.
    # Fixed seeds make the paper's verification reproducible.
    rng = random.Random(42)
    constants_1 = [rng.randrange(256) for _ in range(16)]
    constants_2 = [rng.randrange(256) for _ in range(16)]

    x_structure_1 = generate_first_order_structure(constants_1)
    x_structure_2 = generate_first_order_structure(constants_2)

    # Paper Eq. (12): P' = S^{-1}(L^{-1}(x)).
    plaintexts_1 = preimage_structure(x_structure_1)
    plaintexts_2 = preimage_structure(x_structure_2)

    # Verify the 3-round distinguisher directly.
    balanced_1 = verify_three_round_distinguisher(plaintexts_1, local_keys)
    balanced_2 = verify_three_round_distinguisher(plaintexts_2, local_keys)

    print("\n3-round distinguisher check:")
    print(f"Structure 1: all 16 output bytes balanced = {balanced_1}")
    print(f"Structure 2: all 16 output bytes balanced = {balanced_2}")

    # Encrypt the two structures for four rounds.
    ciphertexts_1 = [encrypt_reduced(p, local_keys) for p in plaintexts_1]
    ciphertexts_2 = [encrypt_reduced(p, local_keys) for p in plaintexts_2]

    recovered, candidates_1, candidates_2, intersections = recover_k4_prime(
        ciphertexts_1, ciphertexts_2
    )

    print("\nBytewise candidate counts:")
    print("pos : after structure 1 -> after structure 2 -> intersection")

    for i in range(16):
        print(
            f"{i:2d}  : "
            f"{len(candidates_1[i]):3d} -> "
            f"{len(candidates_2[i]):3d} -> "
            f"{len(intersections[i]):3d}"
        )

    unique = all(byte is not None for byte in recovered)

    if unique:
        recovered_hex = block_to_hex(recovered)
        recovered_k4 = L(recovered)

        print("\nRecovered transformed last subkey:")
        print(f"K4' = {recovered_hex}")

        print("\nRecovered local last subkey:")
        print(f"K4  = {block_to_hex(recovered_k4)}")

        print("\nVerification:")
        print(f"All 16 bytes uniquely recovered : {recovered == real_k4_prime}")
        print(
            "Matches value reported in paper: "
            f"{recovered_hex == EXPECTED_K4_PRIME_HEX}"
        )

        if recovered != real_k4_prime:
            raise RuntimeError("Recovered K4' does not match the real transformed subkey.")

        if recovered_hex != EXPECTED_K4_PRIME_HEX:
            raise RuntimeError("Recovered K4' does not match the value reported in the paper.")

    else:
        print("\nAt least one byte has multiple surviving candidates.")
        print("A further independent structure can be used for additional filtering.")

    print("\nData used:")
    print("2 independent structures x 2^8 plaintexts = 2^9 chosen plaintexts")
    print("=" * 72)


if __name__ == "__main__":
    main()

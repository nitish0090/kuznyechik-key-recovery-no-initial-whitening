
"""
Kuznyechik integral distinguisher and 4-round subkey recovery
without initial key whitening.

This implementation accompanies the paper:

    "Integral Distinguishers and 4-Round Key-Recovery Attack on
     Kuznyechik Without Initial Key Whitening"

Reduced model used in the paper:
    X_0 = P
    X_r = L(S(X_{r-1})) xor K_r,  r >= 1

For the experimental validation, the local reduced-model keys
K_1, ..., K_4 are instantiated by the first four 128-bit subkeys
generated by the standard Kuznyechik key schedule.

The 3-round distinguisher uses the key-independent preimage
    P' = S^{-1}(L^{-1}(x)),
where x ranges over a first-order (A, C^15) structure.

The 4-round recovery first computes
    Y = L^{-1}(C) = S(X_3) xor K'_4,
with
    K'_4 = L^{-1}(K_4),
and tests each byte of K'_4 independently using the balanced
XOR condition over two independent 2^8-element structures.

No external Python packages are required.
"""


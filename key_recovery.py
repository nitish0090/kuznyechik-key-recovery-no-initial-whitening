INV_SBOX = [0] * 256
for i, value in enumerate(SBOX):
    INV_SBOX[value] = i


# ============================================================
# GF(2^8) arithmetic
# p(x) = x^8 + x^7 + x^6 + x + 1
# lower byte of the reduction polynomial = 0xC3
# ============================================================

RED_POLY = 0xC3


def gf_mul(a: int, b: int) -> int:
    """Multiply two bytes in GF(2^8) with Kuznyechik's polynomial."""
    a &= 0xFF
    b &= 0xFF
    result = 0

    for _ in range(8):
        if b & 1:
            result ^= a

        carry = a & 0x80
        a = (a << 1) & 0xFF
        if carry:
            a ^= RED_POLY

        b >>= 1

    return result & 0xFF


# ============================================================
# Linear layer L = R^16
# ============================================================

R_COEFFS = (
    148, 32, 133, 16, 194, 192, 1, 251,
    1, 192, 194, 16, 133, 32, 148, 1,
)


def R(state):
    """One Kuznyechik R transformation."""
    acc = state[15]
    for j in range(15):
        acc ^= gf_mul(R_COEFFS[j], state[j])
    return [acc] + state[:15]


def R_inv(state):
    """Inverse of one Kuznyechik R transformation."""
    previous_0_to_14 = state[1:]
    previous_15 = state[0]

    for j in range(15):
        previous_15 ^= gf_mul(R_COEFFS[j], previous_0_to_14[j])

    return previous_0_to_14 + [previous_15]


def L(state):
    """Kuznyechik linear transformation L = R^16."""
    out = state[:]
    for _ in range(16):
        out = R(out)
    return out


def L_inv(state):
    """Inverse Kuznyechik linear transformation."""
    out = state[:]
    for _ in range(16):
        out = R_inv(out)
    return out


# ============================================================
# Standard Kuznyechik key schedule
# ============================================================

REFERENCE_MASTER_KEY = (
    0x8899aabbccddeeff0011223344556677
    << 128
) | 0xfedcba98765432100123456789abcdef

EXPECTED_K4_PRIME_HEX = "e60fce12efb4465985875cbea0201d6e"


def int_to_block(value):
    return [(value >> ((15 - i) * 8)) & 0xFF for i in range(16)]


def block_to_hex(block):
    return "".join(f"{b:02x}" for b in block)


def xor16(a, b):
    return [x ^ y for x, y in zip(a, b)]


def F_function(a1, a0, constant):
    temp = xor16(a1, constant)
    temp = [SBOX[b] for b in temp]
    temp = L(temp)
    return xor16(temp, a0), a1


def standard_key_expansion(master_key):
    """
    Return the ten 128-bit Kuznyechik subkeys.

    keys[0], ..., keys[9] are the first through tenth
    subkeys generated by the standard key schedule.
    """
    high = master_key >> 128
    low = master_key & ((1 << 128) - 1)

    k1 = int_to_block(high)
    k2 = int_to_block(low)

    round_keys = [k1, k2]

    constants = [[0] * 16]
    for j in range(1, 33):
        constants.append(L([0] * 15 + [j]))

    a, b = k1[:], k2[:]

    for group in range(4):
        start = 8 * group + 1
        stop = 8 * (group + 1) + 1

        for index in range(start, stop):
            a, b = F_function(a, b, constants[index])

        round_keys.append(a[:])
        round_keys.append(b[:])

    return round_keys


# ============================================================
# Reduced-round model from the paper
#
# X_0 = P
# X_r = L(S(X_{r-1})) xor K_r
#
# No key is added before the first S-box.
# ============================================================

def encrypt_reduced(plaintext, local_keys):
    """Encrypt with the no-initial-whitening reduced model."""
    state = plaintext[:]

    for key in local_keys:
        state = [SBOX[b] for b in state]
        state = L(state)
        state = xor16(state, key)

    return state


# ============================================================
# 3-round integral distinguisher
#
# X = {(t,c1,...,c15) : t in GF(2^8)}
#
# Paper Eq. (12):
#     P' = { S^{-1}(L^{-1}(x)) : x in X }
#
# IMPORTANT:
# The plaintext preimage is key-independent.  No K_1 is used
# in its construction.
# ============================================================

def generate_first_order_structure(constants):
    """
    Generate a 2^8-element structure of type (A, C^15).

    constants must be a 16-byte list.  Its first entry is ignored
    because byte position 0 is the active byte.
    """
    structure = []

    for t in range(256):
        x = constants[:]
        x[0] = t
        structure.append(x)

    return structure


def preimage_structure(structure):
    """
    Compute the key-independent one-round preimage

        P' = S^{-1}(L^{-1}(X)).

    This is exactly the backward construction used in the paper.
    """
    plaintexts = []

    for x in structure:
        state = L_inv(x)
        state = [INV_SBOX[b] for b in state]
        plaintexts.append(state)

    return plaintexts


def byte_xor_sum(states, position):
    total = 0
    for state in states:
        total ^= state[position]
    return total


def all_bytes_balanced(states):
    """Check the bytewise balanced condition Sigma_i = 0 for all 16 bytes."""
    return all(byte_xor_sum(states, i) == 0 for i in range(16))


def verify_three_round_distinguisher(plaintexts, local_keys):
    """
    Encrypt the key-independent preimage structure for three rounds
    and verify that all sixteen output-byte XOR sums are zero.
    """
    outputs = [encrypt_reduced(p, local_keys[:3]) for p in plaintexts]
    return all_bytes_balanced(outputs)


# ============================================================
# 4-round recovery of K'_4 = L^{-1}(K_4)
#
# Y = L^{-1}(C) = S(X_3) xor K'_4
#
# For byte i and guess g:
#
#     T_i(g) = xor_t S^{-1}(Y_i^(t) xor g)
#
# The correct guess satisfies T_i(g) = 0.
# ============================================================

def candidates_for_structure(ciphertexts):
    """
    Return the candidate list for each byte of K'_4 using one
    2^8-element ciphertext structure.
    """
    transformed = [L_inv(c) for c in ciphertexts]
    candidates = []

    for position in range(16):
        position_candidates = []

        for guess in range(256):
            xor_sum = 0

            for y in transformed:
                xor_sum ^= INV_SBOX[y[position] ^ guess]

            if xor_sum == 0:
                position_candidates.append(guess)

        candidates.append(position_candidates)

    return candidates


def recover_k4_prime(ciphertexts_1, ciphertexts_2):
    """
    Intersect the bytewise candidate sets obtained from two
    independent structures.

    If an intersection contains exactly one element, that byte is
    uniquely recovered.  Otherwise all surviving candidates are
    retained, exactly as stated in the revised Algorithm 1.
    """
    candidates_1 = candidates_for_structure(ciphertexts_1)
    candidates_2 = candidates_for_structure(ciphertexts_2)

    intersections = []
    recovered = []

    for position in range(16):
        common = sorted(set(candidates_1[position]) & set(candidates_2[position]))
        intersections.append(common)

        if len(common) == 1:
            recovered.append(common[0])
        else:
            recovered.append(None)

    return recovered, candidates_1, candidates_2, intersections


